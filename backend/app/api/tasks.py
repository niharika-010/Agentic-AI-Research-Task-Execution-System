import json
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, BackgroundTasks, status
from sqlalchemy.orm import Session
from app.db.database import get_db, TaskModel
from app.models.schemas import (
    TaskCreateRequest,
    TaskSummaryResponse,
    TaskDetailResponse,
    TaskPlanResponse,
    TaskResultResponse,
    EventResponse,
    Plan,
    Source,
    ResearchFinding,
    AnalysisOutput,
    ReviewVerdict
)
from app.services.task_service import task_service

router = APIRouter(prefix="/api/tasks", tags=["Tasks"])

@router.post("", response_model=TaskSummaryResponse, status_code=status.HTTP_201_CREATED)
async def create_task(
    request: TaskCreateRequest,
    background_tasks: BackgroundTasks,
    db: Session = Depends(get_db)
):
    """
    Submit a new research task and trigger multi-agent pipeline execution.
    """
    user_query = request.get_query()
    task = task_service.create_task(db, user_query)
    
    # Schedule execution in background
    background_tasks.add_task(task_service.execute_task, task.id)
    return task

@router.get("", response_model=List[TaskSummaryResponse])
def list_tasks(limit: int = 50, db: Session = Depends(get_db)):
    """
    List previous research tasks with their current execution status.
    """
    return task_service.list_tasks(db, limit=limit)

@router.get("/{task_id}", response_model=TaskDetailResponse)
def get_task_details(task_id: str, db: Session = Depends(get_db)):
    """
    Retrieve full task details, including generated artifacts at current stage.
    """
    task = task_service.get_task(db, task_id)
    if not task:
        raise HTTPException(status_code=404, detail="Task not found")

    plan_obj = Plan(**json.loads(task.plan_json)) if task.plan_json else None
    findings_obj = [ResearchFinding(**f) for f in json.loads(task.findings_json)] if task.findings_json else None
    analysis_obj = AnalysisOutput(**json.loads(task.analysis_json)) if task.analysis_json else None
    sources_obj = [Source(**s) for s in json.loads(task.sources_json)] if task.sources_json else None

    return TaskDetailResponse(
        id=task.id,
        user_request=task.user_request,
        status=task.status,
        current_stage=task.current_stage,
        revision_count=task.revision_count,
        created_at=task.created_at,
        updated_at=task.updated_at,
        error_message=task.error_message,
        plan=plan_obj,
        findings=findings_obj,
        analysis=analysis_obj,
        draft_markdown=task.draft_markdown,
        review_feedback=task.review_feedback,
        final_report=task.final_report,
        sources=sources_obj
    )

@router.get("/{task_id}/plan", response_model=TaskPlanResponse)
def get_task_plan(task_id: str, db: Session = Depends(get_db)):
    """
    Retrieve subtasks decomposition generated by the Planner Agent.
    """
    task = task_service.get_task(db, task_id)
    if not task:
        raise HTTPException(status_code=404, detail="Task not found")

    plan_obj = Plan(**json.loads(task.plan_json)) if task.plan_json else None
    return TaskPlanResponse(
        task_id=task.id,
        status=task.status,
        plan=plan_obj
    )

@router.get("/{task_id}/events", response_model=List[EventResponse])
def get_task_events(task_id: str, db: Session = Depends(get_db)):
    """
    Retrieve agent execution event log for live UI polling and execution timeline.
    """
    task = task_service.get_task(db, task_id)
    if not task:
        raise HTTPException(status_code=404, detail="Task not found")

    events = task_service.get_task_events(db, task_id)
    results = []
    for ev in events:
        data = json.loads(ev.data_json) if ev.data_json else None
        results.append(EventResponse(
            id=ev.id,
            task_id=ev.task_id,
            agent_name=ev.agent_name,
            stage=ev.stage,
            event_type=ev.event_type,
            message=ev.message,
            data=data,
            created_at=ev.created_at
        ))
    return results

@router.get("/{task_id}/result", response_model=TaskResultResponse)
def get_task_result(task_id: str, db: Session = Depends(get_db)):
    """
    Retrieve final verified research report, source links, and reviewer decision.
    """
    task = task_service.get_task(db, task_id)
    if not task:
        raise HTTPException(status_code=404, detail="Task not found")

    sources = [Source(**s) for s in json.loads(task.sources_json)] if task.sources_json else []
    
    verdict = None
    if task.review_feedback:
        verdict = ReviewVerdict(
            passed=task.status == "completed",
            score=95 if task.status == "completed" else 75,
            feedback=task.review_feedback
        )

    return TaskResultResponse(
        task_id=task.id,
        status=task.status,
        user_request=task.user_request,
        final_report=task.final_report,
        sources=sources,
        revision_count=task.revision_count,
        review_verdict=verdict
    )
